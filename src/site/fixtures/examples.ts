// Complete sites that ship with the repository. Their pictures are in public/starter,
// so they look finished on a fresh clone with no API key.

import { docFromOps } from '../ops';
import { parseDoc, type SiteDoc } from '../schema';
import { NORTHFOLD_OPS } from './northfold';
import scorchBros from './scorch-bros.json';

export type Example = { id: string; label: string; note: string; load(): SiteDoc };

export const EXAMPLES: Example[] = [
  {
    id: 'scorch-bros',
    label: 'Scorch Bros',
    note: 'Generated by Claude Sonnet 5.5 from a three-sentence brief in 22 seconds. Not edited afterwards.',
    load: () => parseDoc(scorchBros),
  },
  {
    id: 'northfold',
    label: 'Northfold Coffee',
    note: 'Written by hand to exercise the whole vocabulary. Its pictures are generated.',
    load: () => docFromOps(NORTHFOLD_OPS),
  },
];

/** What a fresh clone opens on. Reorder EXAMPLES to change it. */
export const starterDoc = (): SiteDoc => EXAMPLES[0].load();
